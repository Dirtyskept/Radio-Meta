$ErrorActionPreference = 'Stop'

$projectRoot = $PSScriptRoot
$webUiRoot = Join-Path $projectRoot 'WebUI'
$moduleRoot = Join-Path $webUiRoot 'DisplayModules'
$outputPath = Join-Path $webUiRoot 'RadioMetaIntegratedDisplay.js'

$moduleFiles = @(
    'RadioMetaDisplayTrackCache.js',
    'RadioMetaDisplayMediaSessionAdapter.js',
    'RadioMetaDisplayPlayerAdapter.js',
    'RadioMetaDisplayDashboardAdapter.js',
    'RadioMetaDisplayCoordinator.js'
)

$parts = New-Object System.Collections.Generic.List[string]
$parts.Add('/* Generated from WebUI/DisplayModules by Build-DisplayHelper.ps1. Do not edit this file directly. */')
foreach ($fileName in $moduleFiles) {
    $path = Join-Path $moduleRoot $fileName
    if (-not (Test-Path -LiteralPath $path -PathType Leaf)) {
        throw "Radio Meta display component is missing: $path"
    }

    $source = [System.IO.File]::ReadAllText($path)
    $parts.Add($source.Trim())
}

$content = [string]::Join("`n`n", $parts) + "`n"
$content = $content -replace "`r`n", "`n"
$content = $content -replace "`r", "`n"

# Guard against accidentally embedding an incomplete or outdated component bundle.
foreach ($required in @(
    'RadioMetaDisplayTrackCache_v1380',
    'RadioMetaDisplayMediaSessionAdapter_v1380',
    'RadioMetaDisplayPlayerAdapter_v1380',
    'RadioMetaDisplayDashboardAdapter_v1380',
    '__radioMetaIntegratedDisplay_v1323'
)) {
    if ($content.IndexOf($required, [System.StringComparison]::Ordinal) -lt 0) {
        throw "Generated display bundle is missing required marker: $required"
    }
}

$utf8NoBom = New-Object System.Text.UTF8Encoding -ArgumentList $false
[System.IO.File]::WriteAllText($outputPath, $content, $utf8NoBom)
Write-Host "Built Radio Meta display bundle: $outputPath"
Write-Host ("Bytes: {0}; components: {1}" -f ([System.Text.Encoding]::UTF8.GetByteCount($content)), $moduleFiles.Count)
